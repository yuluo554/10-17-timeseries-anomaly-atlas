"""M1 generator tests: two layers (frozen artifact shape, then bit-for-bit regeneration),
plus the RNG's known-answer vectors and the tamper/missing paths that must exit 2.

Layer 1 would pass on a fixture that was hand-edited to look right; layer 2 is what
proves the artifact is reproducible from the recorded seed and parameters.
"""

