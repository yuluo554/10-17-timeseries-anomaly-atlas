from conftest import (
    MANIFEST_JSON,
    REPO_ROOT,
    SERIES_CSV,
    TOOLS,
    TRUTH_HASH,
    TRUTH_JSON,
    iter_floats,
    read_bytes,
    read_text,
)


def _load_generator():
    path = os.path.join(TOOLS, "gen_synthetic_series.py")
    spec = importlib.util.spec_from_file_location("zaa_gen_synthetic_series", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


generator = _load_generator()

_HEADER = "timestamp,series_id,value"
_ARTIFACT_RELATIVE = (
    "data/synthetic/series.csv",
    "data/synthetic/manifest.json",
    "data/truth/truth.json",
    "data/truth/hash.txt",
)


def _manifest():
    return json.loads(read_text(MANIFEST_JSON))


def _truth():
    return json.loads(read_text(TRUTH_JSON))


def _independent_canonical_bytes(obj):
    """The data/README 4.3 rule, written out here rather than imported from canon.py."""
    return (json.dumps(obj, sort_keys=True, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _independent_anomaly_set(truth):
    return {
        "scenario": truth["scenario"],
        "seed": truth["seed"],
        "cadence_ms": truth["cadence_ms"],
        "max_gap_ms": truth["max_gap_ms"],
        "window_points": truth["window_points"],
        "segments": truth["segments"],
    }


def _all_keys(obj, found=None):
    if found is None:
        found = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            found.append(key)
            _all_keys(value, found)
    elif isinstance(obj, (list, tuple)):
        for value in obj:
            _all_keys(value, found)
    return found


def _copy_frozen_tree(destination):
    shutil.copytree(os.path.join(REPO_ROOT, "data"), os.path.join(destination, "data"))
    return str(destination)


class TestRngIsSelfContained:
    def test_splitmix64_matches_the_published_reference_vectors(self):
        # An independent known-answer test: if the mixer drifted, every regenerated byte
        # would still be self-consistent, so only external vectors can catch it.
        stream = generator.SplitMix64(0)
        assert [stream.next_u64() for _ in range(3)] == [
            0xE220A8397B1DCDAF,
            0x6E789E6AA1B965F4,
            0x06C45D188009454F,
        ]
        other = generator.SplitMix64(1234567)
        assert [other.next_u64() for _ in range(2)] == [0x599ED017FB08FC85, 0x2C73F08458540FA5]

    def test_next_unit_is_the_exact_53_bit_construction(self):
        stream = generator.SplitMix64(0)
        first = stream.next_u64()
        expected = (first >> 11) * (1.0 / 9007199254740992.0)
        assert generator.SplitMix64(0).next_unit() == expected
        assert 0.0 <= expected < 1.0

    def test_state_is_masked_to_64_bits(self):
        stream = generator.SplitMix64((1 << 70) + 5)
        assert stream.state == 5
        assert stream.next_u64() < (1 << 64)

    def test_source_does_not_import_the_stdlib_random_module(self):
        source = read_text(os.path.join(TOOLS, "gen_synthetic_series.py"))
        tree = ast.parse(source)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    assert alias.name.split(".")[0] != "random", "K11 forbids stdlib random"
            if isinstance(node, ast.ImportFrom):
                assert (node.module or "").split(".")[0] != "random"

    def test_source_contains_no_transcendental_call(self):
        # The daily cycle is a 24-entry table with linear interpolation precisely so that
        # the whole pipeline stays free of exp/log/pow/sin/cos/sqrt (K4).
        source = read_text(os.path.join(TOOLS, "gen_synthetic_series.py"))
        tree = ast.parse(source)
        forbidden = {"exp", "log", "log2", "log10", "sin", "cos", "tan", "sqrt", "pow", "hypot"}
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute):
                assert node.attr not in forbidden, node.attr
            if isinstance(node, ast.Name):
                assert node.id not in forbidden, node.id
            assert not isinstance(node, ast.Pow), "integer powers must be written as products"


class TestFrozenArtifactShape:
    def test_all_four_artifacts_exist(self):
        for relative in _ARTIFACT_RELATIVE:
            assert os.path.isfile(os.path.join(REPO_ROOT, relative.replace("/", os.sep))), relative

    def test_manifest_ledger_matches_the_bytes_on_disk(self):
        manifest = _manifest()
        assert len(manifest["artifacts"]) == 3
        for entry in manifest["artifacts"]:
            payload = read_bytes(os.path.join(REPO_ROOT, entry["path"].replace("/", os.sep)))
            assert hashlib.sha256(payload).hexdigest() == entry["sha256"], entry["path"]
            assert len(payload) == entry["size_bytes"], entry["path"]
            assert entry["path"] not in ("data/synthetic/manifest.json",), "no self-hash"

    def test_hash_txt_matches_the_manifest_and_an_independent_recomputation(self):
        recorded = read_text(TRUTH_HASH).strip()
        assert re.fullmatch(r"[0-9a-f]{64}", recorded)
        assert recorded == _manifest()["truth_sha256"]
        expected = hashlib.sha256(
            _independent_canonical_bytes(_independent_anomaly_set(_truth()))
        ).hexdigest()
        assert recorded == expected

    def test_manifest_records_every_parameter_the_run_used(self):
        params = _manifest()["params"]
        assert _manifest()["seed"] == generator.DEFAULT_SEED
        for key in (
            "n_grid_points",
            "cadence_ms",
            "period_minutes",
            "window_points",
            "max_gap_ms",
            "value_decimals",
            "start_epoch_ms",
            "start_iso",
            "variance_mult_milli",
        ):
            assert key in params, key
        assert params["start_iso"] == "2024-02-29T00:00:00.000Z"
        assert len(params["series"]) == 3
        for series in params["series"]:
            assert len(series["daily_profile_milli"]) == 24
            assert series["dropped_points"][0] < series["dropped_points"][1]

    def test_manifest_ledger_paths_are_repo_relative_with_forward_slashes(self):
        for entry in _manifest()["artifacts"]:
            assert "\\" not in entry["path"]
            assert entry["path"].startswith("data/")


class TestTruthShape:
    def test_truth_has_no_observed_field_anywhere(self):
        # The truth must record inputs and expectations only; an `observed` key would turn
        # the benchmark into a comparison of two pre-computed answers (plan/04).
        assert "observed" not in _all_keys(_truth())

    def test_truth_carries_no_always_dumb_status_key(self):
        keys = set(_all_keys(_truth()))
        assert not (keys & {"status", "ok", "passed", "verified", "result"})

    def test_truth_contains_only_canonical_json_types(self):
        assert list(iter_floats(_truth())) == []

    def test_scenario_is_marked_as_fictional(self):
        assert _truth()["scenario"] == generator.SCENARIO
        assert "虚构" in _truth()["scenario"]

    def test_every_family_is_planted_at_least_twice(self):
        counts = {}
        for segment in _truth()["segments"]:
            counts[segment["type"]] = counts.get(segment["type"], 0) + 1
        for family in ("spike", "level_shift", "variance_shift", "missing_run", "zero_run"):
            assert counts.get(family, 0) >= 2, (family, counts)
        assert sum(counts.values()) == len(_truth()["segments"])

    def test_at_least_one_segment_sits_on_a_rolling_window_boundary(self):
        boundary = [s for s in _truth()["segments"] if s["at_window_boundary"]]
        assert len(boundary) >= 2, "both window edges should be covered"
        window = _truth()["window_points"]
        grid = _truth()["n_grid_points"]
        for segment in _truth()["segments"]:
            first = (segment["start_ms"] - _truth()["start_epoch_ms"]) // _truth()["cadence_ms"]
            last = (segment["end_ms"] - _truth()["start_epoch_ms"]) // _truth()["cadence_ms"]
            assert segment["at_window_boundary"] == (first < window or last + window > grid)

    def test_merge_probes_straddle_max_gap_ms(self):
        probes = _truth()["merge_probes"]
        assert len(probes) >= 2
        for probe in probes:
            assert probe["max_gap_ms"] == _truth()["max_gap_ms"]
            assert probe["expected_merged"] == (probe["separation_ms"] <= probe["max_gap_ms"])
            expected_side = (
                "at_or_below_max_gap" if probe["separation_ms"] <= probe["max_gap_ms"] else "above_max_gap"
            )
            assert probe["side"] == expected_side
        assert {probe["side"] for probe in probes} == {"at_or_below_max_gap", "above_max_gap"}
        separations = sorted(probe["separation_ms"] for probe in probes)
        assert separations[0] < _truth()["max_gap_ms"] < separations[-1]

    def test_planted_timeline_events_are_present(self):
        planted = _truth()["planted"]
        assert len(planted["duplicate_timestamps"]) >= 1
        assert len(planted["gaps"]) == 3
        assert len(planted["missing_runs"]) == 3
        assert len(planted["zero_runs"]) == 3
        for gap in planted["gaps"]:
            assert gap["interval_ms"] == gap["n_dropped_points"] * _truth()["cadence_ms"] + _truth()["cadence_ms"]

    def test_segment_keys_carry_their_own_conclusion(self):
        for segment in _truth()["segments"]:
            assert segment["type"] in (
                "spike",
                "level_shift",
                "variance_shift",
                "missing_run",
                "zero_run",
            )
            assert segment["magnitude_kind"] in (
                "additive_milli",
                "noise_scale_milli",
                "value_replacement",
            )
            assert segment["n_points"] == (
                (segment["end_ms"] - segment["start_ms"]) // _truth()["cadence_ms"] + 1
            )
            assert segment["n_points"] >= 1


class TestCsvArtifact:
    def test_line_endings_encoding_and_header(self):
        payload = read_bytes(SERIES_CSV)
        assert not payload.startswith(b"\xef\xbb\xbf")
        assert b"\r" not in payload
        assert payload.endswith(b"\n")
        assert payload.decode("utf-8").split("\n")[0] == _HEADER

    def test_row_count_matches_the_truth(self):
        lines = [line for line in read_text(SERIES_CSV).split("\n") if line]
        assert len(lines) - 1 == sum(series["n_rows"] for series in _truth()["series"])

    def test_every_timestamp_parses_and_lands_on_the_grid(self):
        rows = read_text(SERIES_CSV).split("\n")[1:]
        seen = 0
        for line in rows:
            if not line:
                continue
            timestamp = line.split(",")[0]
            epoch_ms = timebase.parse_iso_to_epoch_ms(timestamp)
            assert (epoch_ms - _truth()["start_epoch_ms"]) % _truth()["cadence_ms"] == 0, timestamp
            seen += 1
        assert seen > 2900

    def test_all_four_representation_forms_appear(self):
        texts = [line.split(",")[0] for line in read_text(SERIES_CSV).split("\n")[1:] if line]
        assert any(text.endswith("Z") for text in texts)
        assert any(text.endswith("+08:00") for text in texts)
        assert any(re.match(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}$", text) for text in texts)
        assert all(re.search(r"\.\d{3}", text) for text in texts)

    def test_planted_duplicate_is_really_two_rows_of_one_series(self):
        rows = [line.split(",") for line in read_text(SERIES_CSV).split("\n")[1:] if line]
        planted = _truth()["planted"]["duplicate_timestamps"][0]
        first = rows[planted["row_nos"][0] - 2]
        second = rows[planted["row_nos"][1] - 2]
        assert first[0] == second[0], "the duplicate rows must share a timestamp"
        assert first[1] == second[1] == planted["series_id"]
        assert first[2] != second[2], "the re-transmitted reading must differ, so row order matters"

    def test_empty_value_cells_exist_for_the_missing_runs(self):
        rows = [line.split(",") for line in read_text(SERIES_CSV).split("\n")[1:] if line]
        for run in _truth()["planted"]["missing_runs"]:
            blanks = [
                rows[row_no - 2]
                for row_no in range(run["start_row"], run["end_row"] + 1)
                if len(rows[row_no - 2]) == 3 and rows[row_no - 2][1] == run["series_id"]
            ]
            assert len(blanks) == run["n_points"]
            assert all(cells[2] == "" for cells in blanks)


class TestRegenerationIsBitIdentical:
    def test_build_artifacts_reproduces_every_frozen_byte(self):
        fresh = generator.build_artifacts(generator.DEFAULT_SEED)
        for relative in _ARTIFACT_RELATIVE:
            frozen = read_bytes(os.path.join(REPO_ROOT, relative.replace("/", os.sep)))
            assert fresh[relative] == frozen, relative

    def test_two_in_process_generations_agree(self):
        assert generator.build_artifacts(generator.DEFAULT_SEED) == generator.build_artifacts(
            generator.DEFAULT_SEED
        )

    def test_a_different_seed_produces_different_data(self):
        other = generator.build_artifacts(generator.DEFAULT_SEED + 1)
        assert other["data/synthetic/series.csv"] != read_bytes(SERIES_CSV)

    def test_check_mode_passes_on_the_frozen_tree(self, capsys):
        assert generator.main(["--check"]) == 0
        assert "check ok" in capsys.readouterr().out


class TestCheckModeRejectsDamage:
    def test_tampered_series_csv_is_caught_by_the_ledger(self, tmp_path, capsys):
        root = _copy_frozen_tree(tmp_path)
        target = os.path.join(root, "data", "synthetic", "series.csv")
        with io.open(target, "ab") as handle:
            handle.write(b"2024-03-04T12:00:00.000Z,temperature,-18.00\n")
        assert generator.cmd_check(root, generator.DEFAULT_SEED) == 2
        assert "tampered" in capsys.readouterr().err

    def test_missing_artifact_is_caught(self, tmp_path, capsys):
        root = _copy_frozen_tree(tmp_path)
        os.remove(os.path.join(root, "data", "truth", "truth.json"))
        assert generator.cmd_check(root, generator.DEFAULT_SEED) == 2
        assert "missing frozen artifact" in capsys.readouterr().err

    def test_tampered_hash_txt_is_caught(self, tmp_path, capsys):
        root = _copy_frozen_tree(tmp_path)
        with io.open(os.path.join(root, "data", "truth", "hash.txt"), "wb") as handle:
            handle.write(b"0" * 64 + b"\n")
        assert generator.cmd_check(root, generator.DEFAULT_SEED) == 2

    def test_tampered_manifest_itself_is_caught_by_regeneration(self, tmp_path, capsys):
        # The manifest cannot be in its own ledger, so only the regeneration comparison
        # can catch it; this is exactly the hole layer 2 exists to close.
        root = _copy_frozen_tree(tmp_path)
        path = os.path.join(root, "data", "synthetic", "manifest.json")
        manifest = json.loads(read_bytes(path).decode("utf-8"))
        manifest["params"]["max_gap_ms"] = 600000
        with io.open(path, "wb") as handle:
            handle.write(
                (json.dumps(manifest, sort_keys=True, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
            )
        assert generator.cmd_check(root, generator.DEFAULT_SEED) == 2
        assert "regeneration differs" in capsys.readouterr().err

    def test_missing_manifest_is_caught(self, tmp_path, capsys):
        root = _copy_frozen_tree(tmp_path)
        os.remove(os.path.join(root, "data", "synthetic", "manifest.json"))
        assert generator.cmd_check(root, generator.DEFAULT_SEED) == 2
        assert "manifest is missing" in capsys.readouterr().err


class TestNonTrivialityAssertionHasTeeth:
    """The generator's own guard must reject a truth that would make the benchmark easy."""

    def test_accepts_the_real_truth(self):
        generator.assert_non_trivial(_truth())

    def test_rejects_a_truth_missing_a_family(self):
        truth = _truth()
        truth["segments"] = [s for s in truth["segments"] if s["type"] != "variance_shift"]
        with pytest.raises(AssertionError):
            generator.assert_non_trivial(truth)

    def test_rejects_a_truth_without_a_window_boundary_segment(self):
        truth = _truth()
        for segment in truth["segments"]:
            segment["at_window_boundary"] = False
        with pytest.raises(AssertionError):
            generator.assert_non_trivial(truth)

    def test_rejects_probes_on_only_one_side_of_max_gap(self):
        truth = _truth()
        for probe in truth["merge_probes"]:
            probe["side"] = "above_max_gap"
        with pytest.raises(AssertionError):
            generator.assert_non_trivial(truth)

    def test_rejects_a_truth_without_a_duplicate_timestamp(self):
        truth = _truth()
        truth["planted"]["duplicate_timestamps"] = []
        with pytest.raises(AssertionError):
            generator.assert_non_trivial(truth)
